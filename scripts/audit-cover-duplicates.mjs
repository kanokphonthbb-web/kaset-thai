// pool entry can be a bare Unsplash id ("1234-abcd") or a full URL (e.g. Pexels) — must match
// publish-batch.mts's toCoverUrl() exactly so proposed URLs are byte-identical to what publish-batch writes.
function toCoverUrl(entry) {
  if (entry.startsWith("http")) return entry;
  return `https://images.unsplash.com/photo-${entry}?auto=format&fit=crop&w=1400&q=70`;
}

const rows = (
  await db.execute({
    sql: `SELECT a.slug, a.title, a.coverImage, c.slug catSlug
          FROM Article a LEFT JOIN ArticleCategory c ON a.categoryId=c.id
          WHERE a.status='published' AND a.coverImage IS NOT NULL AND a.coverImage<>''
          ORDER BY c.slug, a.slug`,
    args: [],
  })
).rows;

// Group by catSlug. Identity = the full stored coverImage URL (not an extracted Unsplash id —
// that regex silently dropped every Pexels-hosted cover from detection entirely).
const byCat = {};
for (const r of rows) {
  const cat = r.catSlug || "(none)";
  (byCat[cat] ||= []).push({ slug: r.slug, title: r.title, cover: String(r.coverImage || "") });
}

const plan = [];
let totalDup = 0;
for (const [cat, arts] of Object.entries(byCat)) {
  const countByCover = {};
  for (const a of arts) if (a.cover) countByCover[a.cover] = (countByCover[a.cover] || 0) + 1;
  const dupCovers = new Set(Object.entries(countByCover).filter(([, n]) => n > 1).map(([c]) => c));
  if (dupCovers.size === 0) continue;

  const pool = CAT_IMAGE_POOLS[cat] || [];
  const usedInCat = new Set(arts.map((a) => a.cover).filter(Boolean));
  const proposedThisCat = new Set();
  const firstSeen = new Set(); // keep the first article of each duplicated cover untouched

  for (const a of arts) {
    if (!a.cover || !dupCovers.has(a.cover)) continue;
    if (!firstSeen.has(a.cover)) {
      firstSeen.add(a.cover);
      continue; // this one keeps its current photo
    }
    // pick a replacement: prefer a pool photo not currently used anywhere in this category
    // and not already proposed to another article in this pass
    let candidates = pool.filter((e) => !usedInCat.has(toCoverUrl(e)) && !proposedThisCat.has(toCoverUrl(e)));
    if (candidates.length === 0) candidates = pool.filter((e) => !proposedThisCat.has(toCoverUrl(e)));
    if (candidates.length === 0) candidates = pool; // pool exhausted, allow reuse as last resort
    let hash = 0;
    for (const ch of a.slug) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
    const entry = candidates[hash % candidates.length];
    const newUrl = entry ? toCoverUrl(entry) : null;
    if (newUrl) {
      proposedThisCat.add(newUrl);
      usedInCat.add(newUrl);
      plan.push({
        catSlug: cat,
        slug: a.slug,
        title: a.title,
        currentPhotoId: a.cover,
        proposedPhotoId: newUrl,
        proposedCoverImage: newUrl,
      });
      totalDup++;
    } else {
      plan.push({
        catSlug: cat,
        slug: a.slug,
        title: a.title,
        currentPhotoId: a.cover,
        proposedPhotoId: null,
        note: "no pool defined for this category — manual sourcing needed",
      });
    }
  }
}

