export function extractProductSourceFacts(name: string): string[] {
  const matches = name.match(
    /(?:\d+(?:[.,]\d+)?\s*(?:ชิ้น|ใบ|ชุด|แพ็ก|แพ็ค|กิโลกรัม|กิโล|กก\.?|กรัม|ลิตร|มล\.?|เมตร|เซนติเมตร|ซม\.?|มิลลิเมตร|มม\.?|นิ้ว|PCS|KG|ML))|(?:พลาสติก|สแตนเลส|เหล็ก|อะลูมิเนียม|อลูมิเนียม|ไม้|PVC|PE|PP)|(?:กันน้ำ|พับเก็บได้|มีทุ่นลอยน้ำ|ใช้แบตเตอรี่|ชาร์จไฟ)/giu,
  );
  if (!matches) return [];
  const seen = new Set<string>();
  return matches
    .map((value) => value.replace(/\s+/g, " ").trim())
    .filter((value) => {
      const key = value.toLocaleLowerCase("th-TH");
      if (!value || seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .slice(0, 6);
}

export function buildProductEditorialContent(
  name: string,
  category: string,
): ProductEditorialContent | null {
  const normalizedSourceName = name.normalize("NFC").replace(/ํา/gu, "ำ");
  if (CLEARLY_UNRELATED_PRODUCT_RE.test(normalizedSourceName)) return null;
  if (/^\s*(?:หนังสือ|book\b)|คู่มือการ(?:ปลูก|เลี้ยง|ทำนา|เพาะ)/iu.test(normalizedSourceName)) {
    return null;
  }
  const template = templates.find((candidate) =>
    candidate.matches(normalizedSourceName, category),
  );
  if (!template) return null;
  const safeEquipmentFamilies = new Set([
    "water-test",
    "soil-test",
    "feeder-waterer",
    "sprayer",
    "farm-measurement",
    "irrigation",
    "farm-hand-tool",
    "farm-machine",
  ]);
  if (
    PRODUCT_REVIEW_REQUIRED_RE.test(normalizedSourceName) &&
    !safeEquipmentFamilies.has(template.family)
  ) {
    return null;
  }

  const sourceFacts = extractProductSourceFacts(normalizedSourceName);
  const sourceCheck = sourceFacts.length
    ? ` ข้อมูลในชื่อสินค้าที่ควรตรวจรับให้ตรงกับรายการสั่งซื้อ ได้แก่ ${sourceFacts.join(", ")}.`
    : "";
  return {
    family: template.family,
    whyNeeded: template.whyNeeded,
    benefits: template.benefits,
    usage: template.usage,
    howToChoose: `${template.choose}${sourceCheck}`,
    useCases: template.useCases,
    safetyNote: template.safetyNote,
    sourceFacts,
  };
}
